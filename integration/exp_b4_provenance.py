#!/usr/bin/env python
"""EXP-B4 -- the fixed-SID trainer must prove *which* tokenizer made its SID.

Run:  python -I integration/exp_b4_provenance.py

The gate (plan.md 19.11.4) registered B4: ``FixedSidTrainer`` recorded the
tokenizer checkpoint's hash and the SID's hash, but never compared them with
the SID's registration manifest, so a mispaired checkpoint trained happily.
``sid_refresh.verify_sid_manifest`` already knows how to refuse such a pairing;
this suite asks whether the trainer actually calls it -- and what happens in
the cases where there is no manifest at all.

  [1] correct checkpoint + SID + manifest -> trains (λ=0, the clean path)
  [2] wrong checkpoint + original SID + manifest -> refused before training
  [3] wrong SID + original manifest -> refused before training
  [4] missing manifest -> refused by default; the explicit opt-out is recorded
      and still checks a versioned SID's encoded checkpoint hash
  [5] λ=0 and the cell-#5 (ETE) training paths still work
  [6] an explicit manifest path, and the dataset recorded in it, are honoured
  [7] a SID swapped between construction and ``run()`` is caught before epoch 0
  [8] the CLI exposes the same policy
  [9] a real historical checkpoint + a real ``refresh_sid`` manifest, and a
      real mispaired tokenizer

The fixture is the production shape at miniature scale: a real RQ-VAE
checkpoint, a SID generated by ``sid_refresh.refresh_sid`` (the frozen
generator subprocess), and the sidecar manifest that flow writes. Nothing
here measures recommendation quality; the only training is one T5 epoch on
120 synthetic sequences.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import traceback

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

from tiger_ext import sid_refresh as SR                                  # noqa: E402
from tiger_ext.alt_pipeline import frozen_modules, rqvae_namespace       # noqa: E402
from tiger_ext.fixed_train import (                                      # noqa: E402
    SID_MANIFEST_MISSING, FixedSidError, FixedSidTrainer, SidProvenanceError,
    resolve_sid_manifest, verify_sid_provenance,
)

DATASET = "B4Syn"
DEVICE = os.environ.get("EXP_B4_DEVICE", "cpu")

SYN = dict(n_items=128, dim=32, centres=8, codes=[64, 64, 64], rqvae_batch=128,
           seq_len=6, n_train=120, n_valid=24, n_test=24, seed=0)
RQVAE_CFG = dict(num_emb_list=list(SYN["codes"]), e_dim=32)
T5_CFG = dict(num_layers=2, num_decoder_layers=2, d_model=64, d_ff=256,
              num_heads=4, d_kv=16)
SEED = 2025

RESULTS = []


def check(name, ok, detail=""):
    RESULTS.append((name, bool(ok), detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" -- {detail}" if detail else ""))
    return bool(ok)


def section(title):
    print(f"\n[{title}]")


def raises(fn, exc):
    try:
        fn()
    except exc as e:
        return True, str(e)
    except BaseException as e:                                   # noqa: BLE001
        return False, f"wrong exception {type(e).__name__}: {e}"
    return False, "no exception"


# --------------------------------------------------------------------------- #
# fixture: item table + interactions + a real (tiny) RQ-VAE + a registered SID
# --------------------------------------------------------------------------- #
def build_dataset(root):
    rng = np.random.default_rng(SYN["seed"])
    n, dim = SYN["n_items"], SYN["dim"]
    centres = rng.normal(size=(SYN["centres"], dim)).astype(np.float32) * 2.0
    which = rng.integers(0, SYN["centres"], size=n)
    emb = centres[which] + rng.normal(size=(n, dim)).astype(np.float32) * 0.3

    data_dir = os.path.join(root, DATASET)
    os.makedirs(data_dir, exist_ok=True)
    pd.DataFrame({"ItemID": np.arange(1, n + 1, dtype=np.int64),
                  "embedding": [emb[i] for i in range(n)]}).to_parquet(
        os.path.join(data_dir, "item_emb.parquet"), index=False)

    def interactions(rows):
        history, target = [], []
        for _ in range(rows):
            seq = rng.integers(1, n + 1, size=SYN["seq_len"]).tolist()
            history.append(seq[:-1])
            target.append(seq[-1])
        return pd.DataFrame({"history": history, "target": target})

    for split, rows in (("train", SYN["n_train"]), ("valid", SYN["n_valid"]),
                        ("test", SYN["n_test"])):
        interactions(rows).to_parquet(os.path.join(data_dir, f"{split}.parquet"),
                                      index=False)
    return data_dir


def train_tokenizer(root, data_dir, seed=SYN["seed"], tag="a"):
    """One real RQ-VAE epoch through the frozen Trainer -- a genuine checkpoint."""
    mods = frozen_modules()
    torch = mods["torch"]
    cfg = dict(RQVAE_CFG)
    rqvae = mods["RQVAE"](
        in_dim=SYN["dim"], num_emb_list=cfg["num_emb_list"], e_dim=cfg["e_dim"],
        layers=[512, 256, 128, 64],
        dropout_prob=0.0, bn=False, loss_type="mse", quant_loss_weight=1.0,
        beta=0.25, kmeans_init=True, kmeans_iters=100,
        sk_epsilons=[0, 0, 0.003], sk_iters=50)
    ckpt_dir = os.path.join(root, f"rqvae_ckpt_{tag}")
    args = rqvae_namespace(os.path.join(data_dir, "item_emb.parquet"), ckpt_dir,
                           DEVICE, seed, epochs=1, eval_step=1,
                           batch_size=SYN["rqvae_batch"], num_workers=0,
                           config=cfg)
    data = mods["EmbDataset"](os.path.join(data_dir, "item_emb.parquet"))
    loader = torch.utils.data.DataLoader(data, num_workers=0,
                                         batch_size=args.batch_size, shuffle=True)
    trainer = mods["RQVAETrainer"](args, rqvae, len(loader))
    trainer.fit(loader)
    path = os.path.join(trainer.ckpt_dir, "best_collision_model.pth")
    if not os.path.isfile(path):
        raise RuntimeError(f"fixture tokenizer saved no checkpoint at {path}")
    return path


def build_trainer(root, tag, sid_path, ckpt, **kwargs):
    params = dict(device=DEVICE, rqvae_config=RQVAE_CFG, t5_config=T5_CFG,
                  seed=SEED, num_workers=0, batch_size=64, infer_size=64,
                  beam_size=5, num_epochs=1, early_stop=99)
    params.update(kwargs)
    return FixedSidTrainer(DATASET, root, sid_path, ckpt,
                           os.path.join(root, "run", tag), **params)


# --------------------------------------------------------------------------- #
# [1] the happy path
# --------------------------------------------------------------------------- #
def part1_happy(root, ckpt, sid_path, side):
    section("1 correct checkpoint + SID + manifest -> trains")

    tr = build_trainer(root, "happy", sid_path, ckpt)
    prov = tr.provenance
    check("the trainer records a manifest-backed provenance",
          prov["mode"] == "manifest" and prov["verified"] is True,
          f"mode={prov['mode']} manifest={os.path.basename(prov['manifest'] or '')}")
    check("the manifest is the SID's sidecar",
          prov["manifest"] == os.path.abspath(side)
          and prov["sid_sha256"] == SR.sha256_file(sid_path)
          and prov["ckpt_sha256"] == SR.sha256_file(ckpt),
          f"ckpt {prov['ckpt_sha256'][:12]} / sid {prov['sid_sha256'][:12]}")
    check("the manifest records the dataset the trainer is about to use",
          prov["dataset"] == DATASET and prov["n_items"] == SYN["n_items"]
          and os.path.isfile(prov["data_path"]),
          f"{prov['dataset']} / {prov['n_items']} rows")

    res = tr.run()
    check("a matching pair trains (λ=0: no mount constructed)",
          res["sid_provenance"]["mode"] == "manifest"
          and res["mounts"]["sia"] is False and res["mounts"]["psa"] is False
          and res["num_epochs_executed"] == 1,
          f"epochs={res['num_epochs_executed']} mounts={res['mounts']}")
    check("the frozen inputs are still unchanged after training",
          res["sid_unchanged"] and res["tokenizer_unchanged"])

    with open(os.path.join(root, "run", "happy", "run.json")) as fh:
        run_json = json.load(fh)
    check("run.json carries the provenance evidence",
          run_json["config"]["sid_provenance_mode"] == "manifest"
          and run_json["config"]["sid_manifest"] == os.path.abspath(side)
          and run_json["result"]["sid_provenance"]["verified"] is True)
    return res


# --------------------------------------------------------------------------- #
# [2] the wrong checkpoint
# --------------------------------------------------------------------------- #
def part2_wrong_ckpt(root, sid_path, side, ckpt_a, ckpt_b):
    section("2 wrong checkpoint + original SID + manifest -> refused")

    check("the second tokenizer is a genuinely different checkpoint",
          SR.sha256_file(ckpt_b) != SR.sha256_file(ckpt_a),
          f"{os.path.basename(os.path.dirname(ckpt_b))}")

    run_dir = os.path.join(root, "run", "wrong_ckpt")
    ok, msg = raises(lambda: build_trainer(root, "wrong_ckpt", sid_path, ckpt_b),
                     SidProvenanceError)
    check("the trainer refuses the mispaired checkpoint at construction",
          ok and "does not belong" in msg and "sha256" in msg, msg[:150])
    check("... and it is also a FixedSidError (callers' existing catch works)",
          isinstance_ok(lambda: build_trainer(root, "wrong_ckpt", sid_path, ckpt_b)))
    check("no run directory or training artifact was produced",
          not os.path.exists(run_dir), run_dir)

    ok, msg = raises(lambda: SR.verify_sid_manifest(
        SR.read_sid_manifest(side), ckpt_path=ckpt_b, sid_path_=sid_path),
        SR.SidManifestMismatch)
    check("the refusal is the reused verify_sid_manifest check, not a new one",
          ok and "!= manifest" in msg, msg[:120])


def isinstance_ok(fn):
    try:
        fn()
    except SidProvenanceError as exc:
        return isinstance(exc, FixedSidError)
    except BaseException:                                        # noqa: BLE001
        return False
    return False


# --------------------------------------------------------------------------- #
# [3] the wrong SID
# --------------------------------------------------------------------------- #
def part3_wrong_sid(root, sid_path, side, ckpt_a):
    section("3 wrong SID + original manifest -> refused")

    bad_dir = os.path.join(root, "bad_sid")
    os.makedirs(bad_dir, exist_ok=True)
    bad_sid = os.path.join(bad_dir, os.path.basename(sid_path))
    codes = SR.load_sid(sid_path).copy()
    codes[0, 0] = (codes[0, 0] + 1) % 256                # one token changes
    np.save(bad_sid, codes)
    shutil.copyfile(side, SR.sidecar_path(bad_sid))      # original manifest

    ok, msg = raises(lambda: build_trainer(root, "bad_sid", bad_sid, ckpt_a),
                     SidProvenanceError)
    check("a SID whose contents changed after registration is refused",
          ok and "content changed" in msg, msg[:150])
    check("no run directory was produced for the tampered SID",
          not os.path.exists(os.path.join(root, "run", "bad_sid")))

    # the manifest itself is untouched: the refusal is about the file contents
    check("the copied manifest still matches the *original* SID",
          SR.verify_sid_manifest(SR.read_sid_manifest(side),
                                 sid_path_=sid_path) is True)


# --------------------------------------------------------------------------- #
# [4] no manifest: default refusal + explicit opt-out
# --------------------------------------------------------------------------- #
def part4_missing_manifest(root, ckpt, sid_path):
    section("4 a SID with no manifest is refused unless explicitly allowed")

    plain_dir = os.path.join(root, "plain")
    os.makedirs(plain_dir, exist_ok=True)
    plain = os.path.join(plain_dir, f"{DATASET}_sid.npy")
    shutil.copyfile(sid_path, plain)

    ok, msg = raises(lambda: build_trainer(root, "plain", plain, ckpt),
                     SidProvenanceError)
    check("by default, a missing manifest is a hard error (never a silent skip)",
          ok and SID_MANIFEST_MISSING in msg and "allow_unregistered_sid" in msg,
          msg[:140])
    check("no provenance sidecar was invented for it",
          not os.path.exists(SR.sidecar_path(plain)))

    tr = build_trainer(root, "plain_ok", plain, ckpt,
                       allow_unregistered_sid=True)
    prov = tr.provenance
    check("the explicit opt-out accepts it and says provenance was not verified",
          prov["mode"] == "unregistered" and prov["verified"] is False
          and "not verified" in prov["warning"] and prov["manifest"] is None,
          f"mode={prov['mode']} name_checked={prov['name_checked']}")
    res = tr.run()
    check("the opt-out is recorded in run.json (auditable, not hidden)",
          res["sid_provenance"]["mode"] == "unregistered",
          "mode=unregistered")

    # a versioned name encodes the checkpoint hash -> that is still checked
    sha = SR.sha256_file(ckpt)
    good_name = os.path.join(plain_dir, SR.sid_name(DATASET, 7, sha))
    shutil.copyfile(sid_path, good_name)
    tr = build_trainer(root, "versioned_ok", good_name, ckpt,
                       allow_unregistered_sid=True)
    check("an unregistered SID whose versioned name matches the checkpoint passes",
          tr.provenance["name_checked"] is True, os.path.basename(good_name))

    bad_name = os.path.join(plain_dir, SR.sid_name(DATASET, 7, "deadbeef"))
    shutil.copyfile(sid_path, bad_name)
    ok, msg = raises(lambda: build_trainer(root, "versioned_bad", bad_name, ckpt,
                                           allow_unregistered_sid=True),
                     SidProvenanceError)
    check("an unregistered SID whose versioned name names another checkpoint fails",
          ok and "versioned name" in msg, msg[:140])


# --------------------------------------------------------------------------- #
# [5] the two live training paths
# --------------------------------------------------------------------------- #
def part5_training_paths(root, ckpt, sid_path, clean_result):
    section("5 λ=0 and cell-#5 paths are intact")

    check("λ=0 is the Clean TIGER path (no mounts, provenance recorded)",
          clean_result["mounts"]["sia"] is False
          and clean_result["mounts"]["psa"] is False
          and clean_result["sid_provenance"]["mode"] == "manifest")

    tr = build_trainer(root, "cell5", sid_path, ckpt,
                       lambda_sia=0.1, lambda_psa=0.1, arm="#5 CSG+ETE")
    res = tr.run()
    check("cell #5 (both ETE mounts live) trains with a manifest-backed SID",
          res["mounts"]["sia"] is True and res["mounts"]["psa"] is True
          and res["sid_provenance"]["mode"] == "manifest"
          and res["sid_unchanged"] and res["tokenizer_unchanged"],
          f"arm={res['arm']} epochs={res['num_epochs_executed']}")

    ok, msg = raises(lambda: build_trainer(root, "csg_reject", sid_path, ckpt,
                                           csg=object()), FixedSidError)
    check("csg= is still refused (the provenance guard did not relax it)",
          ok and "not accepted" in msg, msg[:110])


# --------------------------------------------------------------------------- #
# [6] explicit manifest + dataset guard
# --------------------------------------------------------------------------- #
def part6_explicit_manifest(root, ckpt, sid_path, side):
    section("6 an explicit manifest path and the recorded dataset are honoured")

    moved_dir = os.path.join(root, "moved")
    os.makedirs(moved_dir, exist_ok=True)
    moved_sid = os.path.join(moved_dir, "published_sid.npy")
    moved_manifest = os.path.join(moved_dir, "provenance.json")
    shutil.copyfile(sid_path, moved_sid)                 # .npy only, like publish
    shutil.copyfile(side, moved_manifest)

    check("the default lookup finds no sidecar for the published path",
          resolve_sid_manifest(moved_sid) is None)
    ok, _ = raises(lambda: build_trainer(root, "moved_fail", moved_sid, ckpt),
                   SidProvenanceError)
    check("... so it is refused without an explicit manifest", ok)

    tr = build_trainer(root, "moved_ok", moved_sid, ckpt,
                       sid_manifest=moved_manifest)
    check("--sid_manifest reattaches the published SID to its record",
          tr.provenance["mode"] == "manifest"
          and tr.provenance["manifest"] == os.path.abspath(moved_manifest))

    ok, msg = raises(lambda: build_trainer(root, "moved_missing", moved_sid, ckpt,
                                           sid_manifest=os.path.join(root, "nope.json")),
                     SidProvenanceError)
    check("an explicit manifest that does not exist is an error",
          ok and "not found" in msg, msg[:100])

    other = dict(SR.read_sid_manifest(side))
    other["dataset"] = "SomeOtherDataset"
    other_manifest = os.path.join(moved_dir, "other_dataset.json")
    with open(other_manifest, "w") as fh:
        json.dump(other, fh)
    tr = build_trainer(root, "wrong_dataset", moved_sid, ckpt,
                       sid_manifest=other_manifest)
    check("a manifest naming another dataset is surfaced (the hashes still rule)",
          tr.provenance["dataset_matches"] is False
          and tr.provenance["dataset"] == "SomeOtherDataset"
          and tr.provenance["verified"] is True,
          "dataset_matches=False, hashes verified")

    # verify_sid_provenance is usable on its own by a driver script
    prov = verify_sid_provenance(sid_path, ckpt, dataset=DATASET)
    check("the guard is a public, standalone function",
          prov["mode"] == "manifest" and prov["verified"] is True)


# --------------------------------------------------------------------------- #
# [7] swap between construction and run()
# --------------------------------------------------------------------------- #
def part7_toctou(root, ckpt, sid_path, side):
    section("7 a SID swapped before run() is caught before epoch 0")

    swap_dir = os.path.join(root, "swap")
    os.makedirs(swap_dir, exist_ok=True)
    swap_sid = os.path.join(swap_dir, os.path.basename(sid_path))
    shutil.copyfile(sid_path, swap_sid)
    shutil.copyfile(side, SR.sidecar_path(swap_sid))

    tr = build_trainer(root, "swap", swap_sid, ckpt)
    codes = SR.load_sid(swap_sid).copy()
    codes[1, 1] = (codes[1, 1] + 1) % 256
    np.save(swap_sid, codes)                             # replace after __init__

    ok, msg = raises(tr.run, SidProvenanceError)
    check("run() re-verifies provenance and refuses the swapped file",
          ok and "run start" in msg and "content changed" in msg, msg[:140])
    check("no epoch ran and no checkpoint was written",
          not os.path.exists(os.path.join(root, "run", "swap", "last.pth"))
          and not os.path.exists(os.path.join(root, "run", "swap", "run.json")))


# --------------------------------------------------------------------------- #
# [8] CLI policy
# --------------------------------------------------------------------------- #
def part8_cli(root, ckpt, sid_path):
    section("8 the CLI exposes the same policy")

    env = dict(os.environ)
    env["PYTHONPATH"] = REPO + os.pathsep + env.get("PYTHONPATH", "")
    rcfg = json.dumps(RQVAE_CFG)

    def run_cli(sid, tag, extra=()):
        return subprocess.run(
            [sys.executable, "-m", "tiger_ext.fixed_train",
             "--dataset", DATASET, "--data_root", root,
             "--sid_path", sid, "--tokenizer_ckpt", ckpt,
             "--run_dir", os.path.join(root, "run", tag),
             "--device", "cpu", "--num_workers", "0",
             "--num_epochs", "1", "--batch_size", "64", "--infer_size", "64",
             "--beam_size", "5", "--rqvae_config", rcfg, *extra],
            cwd=REPO, env=env, capture_output=True, text=True, timeout=900)

    proc = run_cli(sid_path, "cli_ok")
    check("the CLI trains with a manifest-backed SID",
          proc.returncode == 0
          and os.path.isfile(os.path.join(root, "run", "cli_ok", "run.json")),
          f"rc={proc.returncode} {proc.stderr.strip().splitlines()[-1:] or ''}")

    plain = os.path.join(root, "plain", f"{DATASET}_sid.npy")
    proc = run_cli(plain, "cli_missing")
    check("the CLI fails (non-zero) when the manifest is missing",
          proc.returncode != 0 and SID_MANIFEST_MISSING in proc.stderr,
          f"rc={proc.returncode}")

    proc = run_cli(plain, "cli_optout", ("--allow_unregistered_sid",))
    ok = proc.returncode == 0
    mode = None
    if ok:
        with open(os.path.join(root, "run", "cli_optout", "run.json")) as fh:
            mode = json.load(fh)["config"]["sid_provenance_mode"]
    check("--allow_unregistered_sid is the recorded, explicit escape hatch",
          ok and mode == "unregistered", f"rc={proc.returncode} mode={mode}")


# --------------------------------------------------------------------------- #
# [9] real historical inputs
# --------------------------------------------------------------------------- #
REAL_CKPT = os.path.join(REPO, "rqvae", "ckpt", "Toys_TA_SID_seed2025",
                         "Sep-03-2026_22-07-02", "best_collision_model.pth")
REAL_OTHER_CKPT = os.path.join(REPO, "clean_tiger", "ckpt", "Toys", "rqvae",
                               "Oct-14-2026_05-55-09", "best_collision_model.pth")
REAL_TABLE = os.path.join(REPO, "data", "Toys", "fused_item_emb_768d.parquet")


def part9_real(root):
    section("9 a real historical checkpoint + a real refresh_sid manifest")

    base = os.path.join(root, "real_sid")
    rec = SR.refresh_sid("Toys", REAL_CKPT, base, device="cpu", timeout=1800)
    side = SR.sidecar_path(rec["sid_path"])
    check("refresh_sid registered a real Toys SID with a manifest",
          os.path.isfile(side) and rec["n_items"] == 11924,
          f"{os.path.basename(rec['sid_path'])} ({rec['n_items']} rows)")

    # the data root the trainer needs: the *same* 768d table the checkpoint read
    real_root = os.path.join(root, "real_data")
    ddir = os.path.join(real_root, "Toys")
    os.makedirs(ddir, exist_ok=True)
    os.symlink(REAL_TABLE, os.path.join(ddir, "item_emb.parquet"))
    for split in ("train", "valid", "test"):
        os.symlink(os.path.join(REPO, "data", "Toys", f"{split}.parquet"),
                   os.path.join(ddir, f"{split}.parquet"))

    tr = FixedSidTrainer("Toys", real_root, rec["sid_path"], REAL_CKPT,
                         os.path.join(root, "run", "real"), device="cpu",
                         num_epochs=0)
    check("the real checkpoint/SID/manifest triple is accepted",
          tr.provenance["mode"] == "manifest"
          and tr.provenance["ckpt_sha256"] == SR.sha256_file(REAL_CKPT)
          and tr.provenance["n_items"] == 11924,
          f"ckpt {tr.provenance['ckpt_sha256'][:12]} / "
          f"{tr.provenance['n_items']} items")

    ok, msg = raises(lambda: FixedSidTrainer(
        "Toys", real_root, rec["sid_path"], REAL_OTHER_CKPT,
        os.path.join(root, "run", "real_bad"), device="cpu", num_epochs=0),
        SidProvenanceError)
    check("a different real tokenizer is refused before any model is trained",
          ok and "does not belong" in msg, msg[:140])


# --------------------------------------------------------------------------- #
# main
# --------------------------------------------------------------------------- #
def main():
    root = tempfile.mkdtemp(prefix="exp_b4_")
    print(f"EXP-B4 workdir: {root}")
    try:
        data_dir = build_dataset(root)
        ckpt_a = train_tokenizer(root, data_dir, seed=SYN["seed"], tag="a")
        ckpt_b = train_tokenizer(root, data_dir, seed=SYN["seed"] + 999, tag="b")
        print(f"  tokenizer A -> {ckpt_a}\n  tokenizer B -> {ckpt_b}")

        rec = SR.refresh_sid(DATASET, ckpt_a, root, device="cpu", timeout=900)
        sid_path = rec["sid_path"]
        side = SR.sidecar_path(sid_path)
        check("the fixture SID was registered by refresh_sid (a real manifest)",
              os.path.isfile(sid_path) and os.path.isfile(side)
              and rec["n_items"] == SYN["n_items"],
              f"{os.path.basename(sid_path)} ({rec['n_items']} rows)")

        clean = part1_happy(root, ckpt_a, sid_path, side)
        part2_wrong_ckpt(root, sid_path, side, ckpt_a, ckpt_b)
        part3_wrong_sid(root, sid_path, side, ckpt_a)
        part4_missing_manifest(root, ckpt_a, sid_path)
        part5_training_paths(root, ckpt_a, sid_path, clean)
        part6_explicit_manifest(root, ckpt_a, sid_path, side)
        part7_toctou(root, ckpt_a, sid_path, side)
        part8_cli(root, ckpt_a, sid_path)
        part9_real(root)
    except BaseException:                                        # noqa: BLE001
        traceback.print_exc()
        RESULTS.append(("harness completed", False, "crashed"))

    passed = sum(1 for _, ok, _ in RESULTS if ok)
    print(f"\nEXP-B4: {passed}/{len(RESULTS)} checks passed")
